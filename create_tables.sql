-- Skema PostgreSQL berdasarkan database.txt
-- Jalankan pada database portal_polinema melalui pgAdmin Query Tool.

CREATE TABLE IF NOT EXISTS semester_akademik (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tahun INTEGER NOT NULL,
    semester VARCHAR(1) NOT NULL CHECK (semester IN ('1', '2', '3', '4', '5', '6', '7', '8')),
    tanggal_mulai DATE,
    tanggal_selesai DATE,
    is_aktif BOOLEAN DEFAULT FALSE
);

CREATE TABLE IF NOT EXISTS kelas (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mata_kuliah_id INTEGER NOT NULL,
    semester_akademik_id INTEGER NOT NULL,
    kurikulum_id INTEGER NOT NULL,
    kode_kelas VARCHAR(20) NOT NULL,
    kapasitas INTEGER,
    status VARCHAR(10) DEFAULT 'aktif' CHECK (status IN ('aktif', 'nonaktif'))
);

CREATE TABLE IF NOT EXISTS dosen_kelas (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kelas_id INTEGER NOT NULL,
    dosen_id INTEGER NOT NULL,
    peran VARCHAR(10) DEFAULT 'pengampu' CHECK (peran IN ('pengampu', 'asisten'))
);

CREATE TABLE IF NOT EXISTS mahasiswa (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nim VARCHAR(14) NOT NULL UNIQUE,
    nama VARCHAR(50) NOT NULL,
    program_studi_id INTEGER NOT NULL,
    kurikulum_id INTEGER NOT NULL,
    angkatan INTEGER NOT NULL,
    status VARCHAR(10) DEFAULT 'aktif' CHECK (status IN ('aktif', 'cuti', 'lulus', 'drop_out'))
);

CREATE TABLE IF NOT EXISTS krs (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mahasiswa_id INTEGER NOT NULL,
    kelas_id INTEGER NOT NULL,
    semester_akademik_id INTEGER NOT NULL,
    status_krs VARCHAR(10) DEFAULT 'pending' CHECK (status_krs IN ('pending', 'approved', 'rejected')),
    nilai_huruf VARCHAR(2),
    nilai_angka REAL
);

CREATE TABLE IF NOT EXISTS jadwal_kelas (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kelas_id INTEGER NOT NULL,
    ruangan_id INTEGER NOT NULL,
    hari VARCHAR(10) NOT NULL CHECK (hari IN ('senin', 'selasa', 'rabu', 'kamis', 'jumat', 'sabtu', 'minggu')),
    jam_mulai TIME NOT NULL,
    jam_selesai TIME NOT NULL,
    tipe_sesi VARCHAR(12) DEFAULT 'kuliah' CHECK (tipe_sesi IN ('kuliah', 'praktikum', 'ujian'))
);

CREATE TABLE IF NOT EXISTS ruangan (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kode VARCHAR(12) NOT NULL UNIQUE,
    nama VARCHAR(50) NOT NULL,
    tipe VARCHAR(12) DEFAULT 'kelas' CHECK (tipe IN ('kelas', 'lab', 'auditorium')),
    kapasitas INTEGER
);

CREATE TABLE IF NOT EXISTS jurnal (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    judul VARCHAR(255) NOT NULL,
    slug VARCHAR(255) NOT NULL UNIQUE,
    gambar VARCHAR(255),
    link VARCHAR(255)
);
